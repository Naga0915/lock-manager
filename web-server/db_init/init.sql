CREATE TABLE IF NOT EXISTS users(
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_str VARCHAR(30) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(320),
    phone VARCHAR(20),
    password_hash TEXT NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT true,
    CHECK (email IS NOT NULL OR phone IS NOT NULL)
);
CREATE TABLE IF NOT EXISTS res(
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    start_time_utc TIMESTAMP WITH TIME ZONE NOT NULL,
    end_time_utc TIMESTAMP WITH TIME ZONE NOT NULL,
    user_id INT NOT NULL,
    lock_id INT NOT NULL
);
CREATE TABLE IF NOT EXISTS lock_hist(
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    datetime_utc TIMESTAMP WITH TIME ZONE NOT NULL,
    user_id INT NOT NULL,
    lock_id INT NOT NULL,
    ops VARCHAR NOT NULL
);
CREATE TABLE IF NOT EXISTS lock_state(
    id INT GENERATED BY DEFAULT as IDENTITY PRIMARY KEY,
    state VARCHAR(1) NOT NULL
);
CREATE TABLE IF NOT EXISTS new_user_url(
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid_str TEXT NOT NULL,
    created TIMESTAMP WITH TIME ZONE NOT NULL,
    expire TIMESTAMP WITH TIME ZONE NOT NULL,
    ip_address TEXT,
    user_agent TEXT
);
CREATE TABLE IF NOT EXISTS reset_password(
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid_str TEXT NOT NULL,
    created TIMESTAMP WITH TIME ZONE NOT NULL,
    expire TIMESTAMP WITH TIME ZONE NOT NULL,
    ip_address TEXT,
    user_agent TEXT
);